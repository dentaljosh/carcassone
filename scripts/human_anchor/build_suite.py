"""4.1 — Expert-position suite builder + renderer + scorer.

Produces a JSONL "expert suite" of 200-500 Carcassonne positions for two uses:
  1. HUMAN-ANCHOR: sit a strong/expert human at each position, record their move,
     score the regret vs the agent's ground truth (objective at K<=4, search-
     labeled midgame).
  2. ANALYZER VALIDATION: this SAME suite is the Phase-5 analyzer's held-out set
     (a move-quality analyzer must reproduce the exact/search regret ranking).

Two kinds of position, one record schema (`exact` flags which):
  (a) ENDGAME (exact=True): K<=4 roots carrying the exact-solver `child_values`
      (endgame_solver.solve). Objective per-action values => objective regret.
      * K=2 (150 roots) come FREE from the on-disk solver cache
        measurement/pre_tool_audit/k2_childvalues.jsonl (no solve needed).
      * K=3/4 are generated by CALLING solve() on replayable source games
        (l23_k4_multisource.jsonl / l23_positions.jsonl). That is CPU-heavy and
        is GUARDED behind --run-solver ("needs boxes"); resumable per gen_id.
  (b) MIDGAME (exact=False): stratified positions (farm fights, meeple scarcity,
      merges/closure races, generic) labeled by the STRONGEST available search
      (champion clairvoyant HeuristicMCTS @ h6400) -> best move + per-action root
      Q. Flagged non-exact. Search labeling is also GUARDED (heavy).

Record schema (one JSON object per line):
  {
    "id": "k2_g3200000000_p140",
    "provenance": {"deck_seed": int, "ply": int, "replay": "greedy"|"actions",
                   "actions": [int...]?, "source": str},
    "stratum": "endgame_k2" | "farm_fight" | "meeple_scarcity" |
               "closure_race" | "midgame_generic",
    "k_remaining": int, "to_move": int, "phase": "tiles"|"meeples",
    "in_hand_tile": str|None, "scores": [int,int],
    "exact": bool,
    "child_values": {action_id(str): value},   # exact only (P0-perspective)
    "optimal_actions": [int...],                # exact only
    "vstar": float,                             # exact only
    "best_move": int,                           # both (label / an optimal action)
    "label": {"agent": str, "sims": int, "child_q": {aid:str: q}}|None,  # midgame
    "legal_moves": [int...]
  }

Usage:
  # prove the pipeline (RUNS: builds 3 exact + 2 midgame, renders, scores fake human):
  .venv/bin/python scripts/human_anchor/build_suite.py --self-test

  # cheap exact suite from the on-disk K=2 cache (no solver, no boxes):
  .venv/bin/python scripts/human_anchor/build_suite.py --from-cache --out measurement/human_anchor/suite.jsonl

  # HEAVY (needs boxes): solve K=3/4 endgames + label midgames
  .venv/bin/python scripts/human_anchor/build_suite.py --generate --run-solver --ks 3 4 --out ...
  .venv/bin/python scripts/human_anchor/build_suite.py --render --suite S.jsonl
  .venv/bin/python scripts/human_anchor/build_suite.py --score --suite S.jsonl --choices human.json
"""
from __future__ import annotations

