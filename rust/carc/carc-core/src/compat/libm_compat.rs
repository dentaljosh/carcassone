#[inline(always)]
fn fma_or<const FMA: bool>(a: f64, b: f64, c: f64) -> f64 {
    if FMA {
        a.mul_add(b, c)
    } else {
        a * b + c
    }
}

#[inline]
fn expm1_inline<const GLIBC: bool, const FMA: bool>(mut x: f64) -> f64 {
    let mut hx = high_word(x);
    let xsb = hx & 0x8000_0000; // sign bit of x
    hx &= 0x7fff_ffff; // high word of |x|

    // filter out huge and non-finite argument
    if hx >= 0x4043_687A {
        // |x| >= 56*ln2
        if hx >= 0x4086_2E42 {
            // |x| >= 709.78...
            if hx >= 0x7ff0_0000 {
                if ((hx & 0xf_ffff) | low_word(x)) != 0 {
                    return x + x; // NaN
                }
                return if xsb == 0 { x } else { -1.0 }; // exp(+-inf) = {inf, -1}
            }
            if x > O_THRESHOLD {
                return HUGE * HUGE; // overflow
            }
        }
        if xsb != 0 {
            // x < -56*ln2, return -1.0 with inexact
            if x + TINY < 0.0 {
                return TINY - ONE;
            }
        }
    }

    let k: i32;
    let mut c = 0.0f64;
    // argument reduction
    if hx > 0x3fd6_2e42 {
        // |x| > 0.5 ln2
        let hi: f64;
        let lo: f64;
        if hx < 0x3FF0_A2B2 {
            // and |x| < 1.5 ln2
            if xsb == 0 {
                hi = x - LN2_HI;
                lo = LN2_LO;
                k = 1;
            } else {
                hi = x + LN2_HI;
                lo = -LN2_LO;
                k = -1;
            }
        } else {
            k = fma_or::<FMA>(INVLN2, x, if xsb == 0 { 0.5 } else { -0.5 }) as i32;
            let t = k as f64;
            hi = fma_or::<FMA>(-t, LN2_HI, x); // t*ln2_hi is exact here
            lo = t * LN2_LO;
        }
        x = hi - lo;
        c = (hi - x) - lo;
    } else if hx < 0x3c90_0000 {
        // |x| < 2**-54, return x
        let t = HUGE + x;
        return x - (t - (HUGE + x));
    } else {
        k = 0;
    }

    // x is now in primary range
    let hfx = 0.5 * x;
    let hxs = x * hfx;
    let r1 = if GLIBC {
        // glibc: R1 = 1 + hxs*Q1; h2 = hxs*hxs; R2 = Q2 + hxs*Q3; h4 = h2*h2;
        //        R3 = Q4 + hxs*Q5; r1 = R1 + h2*R2 + h4*R3;
        let rr1 = fma_or::<FMA>(hxs, Q1, ONE);
        let h2 = hxs * hxs;
        let rr2 = fma_or::<FMA>(hxs, Q3, Q2);
        let h4 = h2 * h2;
        let rr3 = fma_or::<FMA>(hxs, Q5, Q4);
        fma_or::<FMA>(h4, rr3, fma_or::<FMA>(h2, rr2, rr1))
    } else {
        // msun/fdlibm: plain Horner
        fma_or::<FMA>(
            hxs,
            fma_or::<FMA>(
                hxs,
                fma_or::<FMA>(hxs, fma_or::<FMA>(hxs, fma_or::<FMA>(hxs, Q5, Q4), Q3), Q2),
                Q1,
            ),
            ONE,
        )
    };
    let t = fma_or::<FMA>(-r1, hfx, 3.0);
    let mut e = hxs * ((r1 - t) / fma_or::<FMA>(-x, t, 6.0));
    if k == 0 {
        return x - fma_or::<FMA>(x, e, -hxs); // c is 0
    }
    let twopk = insert_words(((0x3ff + k) as u32) << 20, 0); // 2^k
    e = fma_or::<FMA>(x, e - c, -c);
    e -= hxs;
    if k == -1 {
        return 0.5 * (x - e) - 0.5;
    }
    if k == 1 {
        if x < -0.25 {
            return -2.0 * (e - (x + 0.5));
        }
        return ONE + 2.0 * (x - e);
    }
    let y: f64;
    if k <= -2 || k > 56 {
        // suffice to return exp(x) - 1
        let mut yy = ONE - (e - x);
        if k == 1024 {
            yy = yy * 2.0 * f64::from_bits(0x7FE0000000000000); // 0x1p1023
        } else {
            yy *= twopk;
        }
        return yy - ONE;
    }
    let mut t = ONE;
    if k < 20 {
        t = set_high_word(t, 0x3ff0_0000 - (0x20_0000u32 >> k)); // t = 1 - 2^-k
        y = (t - (e - x)) * twopk;
    } else {
        t = set_high_word(t, ((0x3ff - k) as u32) << 20); // t = 2^-k
        let mut yy = x - (e + t);
        yy += ONE;
        y = yy * twopk;
    }
    y
}

