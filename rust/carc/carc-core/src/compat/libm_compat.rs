//! Double-precision `exp` and `tanh` ported to Rust so the search does not
//! depend on the platform libm.
//!
//! **These are HYPOTHESES.** The port is faithful to a named upstream; whether a
//! given platform's `np.exp` / `math.tanh` actually *is* that upstream is what
//! `scripts/rustport/harness_transcendental.py` measures. Do not adjust the code
//! to chase a mismatch — record the mismatch.
//!
//! Provenance
//! ----------
//! * [`exp64`] — ARM optimized-routines `math/exp.c` (`exp_inline(x, 0, 0)`),
//!   `EXP_TABLE_BITS = 7`, `EXP_POLY_ORDER = 5`, `TOINT_INTRINSICS = 0`,
//!   `EXP_USE_TOINT_NARROW = 0`. This is the implementation glibc adopted for
//!   `exp()` in 2.27 (`sysdeps/ieee754/dbl-64/e_exp.c`) and the common ancestor
//!   of what bionic ships. Data table: [`super::exp_data`], generated by
//!   `scripts/rustport/gen_exp_table.py`.
//!   <https://github.com/ARM-software/optimized-routines>
//!   SPDX: MIT OR Apache-2.0 WITH LLVM-exception, Copyright (c) 2018-2019 Arm Limited.
//! * [`tanh64`] / [`expm1_64`] — fdlibm / FreeBSD msun `s_tanh.c` and `s_expm1.c`.
//!   Copyright (C) 1993 by Sun Microsystems, Inc. glibc's
//!   `sysdeps/ieee754/dbl-64/s_tanh.c` is this same code, as is bionic's (via
//!   FreeBSD msun).
//!
//! FMA contraction
//! ---------------
//! glibc on x86-64 ships an ifunc-selected `__exp_fma` built from the *same*
//! source with `-mfma -mavx2`, which lets the compiler contract
//! `x + kd*NegLn2hiN + kd*NegLn2loN` and the polynomial into FMAs — a different
//! function of the same input. aarch64 always has FMA available. Rust never
//! contracts implicitly, so [`exp64`] is the *non-contracted* build and
//! [`exp64_fma`] is the contracted one. The harness reports which (if either)
//! reproduces the local `np.exp`; that is the G0 dispatch finding.

use super::exp_data as d;

#[inline(always)]
fn as_u64(x: f64) -> u64 {
    x.to_bits()
}
#[inline(always)]
fn as_f64(x: u64) -> f64 {
    f64::from_bits(x)
}
/// Top 12 bits of a double (sign and exponent bits).
#[inline(always)]
fn top12(x: f64) -> u32 {
    (as_u64(x) >> 52) as u32
}

/// `specialcase` from ARM `exp.c` — the overflow/underflow-adjacent tail.
fn exp_specialcase(tmp: f64, mut sbits: u64, ki: u64) -> f64 {
    if (ki & 0x8000_0000) == 0 {
        // k > 0, the exponent of scale might have overflowed by <= 460.
        sbits = sbits.wrapping_sub(1009u64 << 52);
        let scale = as_f64(sbits);
        return P1009 * (scale + scale * tmp);
    }
    // k < 0, need special care in the subnormal range.
    sbits = sbits.wrapping_add(1022u64 << 52);
    let scale = as_f64(sbits);
    let mut y = scale + scale * tmp;
    if y < 1.0 {
        // Round y to the right precision before scaling it into the subnormal
        // range to avoid double rounding.
        let mut lo = scale - y + scale * tmp;
        let hi = 1.0 + y;
        lo = 1.0 - hi + y + lo;
        y = (hi + lo) - 1.0;
        // Avoid -0.0 with downward rounding.
        if y == 0.0 {
            y = 0.0;
        }
    }
    PM1022 * y
}

const P1009: f64 = f64::from_bits(0x7F00000000000000); // 0x1p1009
const PM1022: f64 = f64::from_bits(0x0010000000000000); // 0x1p-1022
const PM54: f64 = f64::from_bits(0x3C90000000000000); // 0x1p-54

/// `exp(x)` — ARM optimized-routines, **without** FMA contraction.
pub fn exp64(x: f64) -> f64 {
    exp_inline::<false>(x)
}

/// `exp(x)` — the same algorithm with the multiply-adds contracted into FMAs,
/// modelling glibc's `-mfma` x86-64 ifunc variant and aarch64 codegen.
pub fn exp64_fma(x: f64) -> f64 {
    exp_inline::<true>(x)
}

#[inline]
fn exp_inline<const FMA: bool>(x: f64) -> f64 {
    let mut abstop = top12(x) & 0x7ff;
    if abstop.wrapping_sub(top12(PM54)) >= top12(512.0).wrapping_sub(top12(PM54)) {
        if abstop.wrapping_sub(top12(PM54)) >= 0x8000_0000 {
            // Avoid spurious underflow for tiny x. (0 is a common input.)
            return 1.0 + x;
        }
        if abstop >= top12(1024.0) {
            if as_u64(x) == as_u64(f64::NEG_INFINITY) {
                return 0.0;
            }
            if abstop >= top12(f64::INFINITY) {
                return 1.0 + x;
            }
            if as_u64(x) >> 63 != 0 {
                return 0.0; // __math_uflow(0)
            }
            return f64::INFINITY; // __math_oflow(0)
        }
        // Large x is special cased below.
        abstop = 0;
    }

    // exp(x) = 2^(k/N) * exp(r), with exp(r) in [2^(-1/2N), 2^(1/2N)].
    let z = d::INV_LN2_N * x;
    // !TOINT_INTRINSICS && !EXP_USE_TOINT_NARROW
    let kd0 = z + d::SHIFT;
    let ki = as_u64(kd0);
    let kd = kd0 - d::SHIFT;

    let r = if FMA {
        // glibc's -mfma build contracts these two multiply-adds.
        kd.mul_add(d::NEG_LN2_LO_N, kd.mul_add(d::NEG_LN2_HI_N, x))
    } else {
        x + kd * d::NEG_LN2_HI_N + kd * d::NEG_LN2_LO_N
    };

    // 2^(k/N) ~= scale * (1 + tail).
    let idx = (2 * (ki % d::N)) as usize;
    let top = ki << (52 - d::EXP_TABLE_BITS);
    let tail = as_f64(d::TAB[idx]);
    // Only a valid scale when -1023*N < k < 1024*N.
    let sbits = d::TAB[idx + 1].wrapping_add(top);

    let r2 = r * r;
    // EXP_POLY_ORDER == 5:
    //   tmp = tail + r + r2 * (C2 + r * C3) + r2 * r2 * (C4 + r * C5);
    let tmp = if FMA {
        let a = r.mul_add(d::C3, d::C2);
        let b = r.mul_add(d::C5, d::C4);
        (r2 * r2).mul_add(b, r2.mul_add(a, tail + r))
    } else {
        tail + r + r2 * (d::C2 + r * d::C3) + r2 * r2 * (d::C4 + r * d::C5)
    };

    if abstop == 0 {
        return exp_specialcase(tmp, sbits, ki);
    }
    let scale = as_f64(sbits);
    if FMA {
        scale.mul_add(tmp, scale)
    } else {
        scale + scale * tmp
    }
}

